# Installs workspace dependencies and writes local dev env files using only
# public/safe values. Real secrets (service-role key, backend signer key,
# Gemini/LiveKit/Kotani keys) are intentionally left blank so they can be
# supplied as Cloud Agent secrets without being committed.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

echo "[setup] Installing workspace dependencies (npm ci)..."
npm ci

