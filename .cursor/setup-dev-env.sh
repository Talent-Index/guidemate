PUBLIC_FUJI_RPC_URL="https://api.avax-test.network/ext/bc/C/rpc"
PUBLIC_MOCK_USDC_ADDRESS="0x76EC76a347115afa9a3490a256bA13447cfBd8c5"
PUBLIC_ESCROW_ADDRESS="0x4837EfB8422143fdaa4f60805fC05a21cc9966C0"

# Prefer real secrets from the environment when present (Cloud Agent secrets),
# otherwise fall back to safe local dev defaults.
DEV_WALLET_ENCRYPTION_KEY="${WALLET_ENCRYPTION_KEY:-$(node -e "console.log(require('crypto').randomBytes(32).toString('hex'))")}"
